// Scans the photos/ folder and regenerates photos-data.js.
//
// Usage:
//   1. Create a subfolder per month you have pictures for, named YYYY-MM, e.g.:
//        photos/2026-07/
//        photos/2024-12/
//   2. Drop any number of image files into those folders (jpg, jpeg, png, gif,
//      webp, avif). Filenames don't matter, they're sorted alphabetically.
//   3. Run:  node build-manifest.js
//   4. Commit + push. GitHub Pages serves the new photos automatically.
//
// Months you never create a folder for just show demo placeholder colors on
// the shelf instead of real photos.

const fs = require('fs');
const path = require('path');

const PHOTOS_DIR = path.join(__dirname, 'photos');
const OUT_FILE = path.join(__dirname, 'photos-data.js');
const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.gif', '.webp', '.avif']);
const FOLDER_RE = /^(\d{4})-(\d{2})$/;

function build() {
  const manifest = {};

  if (!fs.existsSync(PHOTOS_DIR)) {
    fs.mkdirSync(PHOTOS_DIR);
  }

  const entries = fs.readdirSync(PHOTOS_DIR, { withFileTypes: true })
    .filter(e => e.isDirectory())
    .map(e => e.name)
    .sort();

  let total = 0;

  for (const folderName of entries) {
    const match = FOLDER_RE.exec(folderName);
    if (!match) {
      console.warn(`Skipping "${folderName}" (expected YYYY-MM, e.g. 2026-07)`);
      continue;
    }
    const year = parseInt(match[1], 10);
    const monthIdx = parseInt(match[2], 10) - 1; // 0-11 to match MONTHS array

    const folderPath = path.join(PHOTOS_DIR, folderName);
    const files = fs.readdirSync(folderPath)
      .filter(f => IMAGE_EXT.has(path.extname(f).toLowerCase()))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

    if (files.length === 0) continue;

    manifest[`${year}-${monthIdx}`] = files.map(f => `photos/${folderName}/${f}`);
    total += files.length;
    console.log(`${folderName}: ${files.length} photo(s)`);
  }

  const contents =
    '// AUTO-GENERATED by build-manifest.js — do not edit by hand.\n' +
    '// Re-run `node build-manifest.js` after adding/removing photos.\n' +
    'const PHOTOS = ' + JSON.stringify(manifest, null, 2) + ';\n';

  fs.writeFileSync(OUT_FILE, contents);
  console.log(`\nWrote ${OUT_FILE} (${total} photo(s) across ${Object.keys(manifest).length} month(s))`);
}

build();
