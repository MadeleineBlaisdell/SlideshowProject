// Scans the photos/ folder and regenerates photos-data.js.
//
// Usage:
//   1. Create a subfolder per person, e.g.:
//        photos/John/
//        photos/Grandma Rose/
//   2. Inside each person's folder, create one subfolder per "book" (album) —
//      any name you like, e.g.:
//        photos/John/Road Trip 2019/
//        photos/John/Birthday/
//   3. Drop any number of image files into those book folders (jpg, jpeg, png,
//      gif, webp, avif). Filenames don't matter, they're sorted alphabetically.
//   4. Run:  node build-manifest.js
//   5. Commit + push. GitHub Pages serves the new photos automatically.
//
// Photos placed directly in photos/ or directly in a person's folder (i.e.
// not inside a book subfolder) are skipped — the script will warn about them.
//
// To go back to the old date-based layout (photos/YYYY-MM/*.jpg, one shelf
// per year with 12 fixed month-books), see buildByDate() below — it's kept
// here, unused, in case you want to switch back. Just change the call at the
// bottom of this file from buildByPerson() to buildByDate(), and restore the
// matching index.html renderer from git history (this JS alone won't bring
// the old UI back — index.html also has an old/new renderer kept side by
// side for the same reason).

const fs = require('fs');
const path = require('path');

const PHOTOS_DIR = path.join(__dirname, 'photos');
const OUT_FILE = path.join(__dirname, 'photos-data.js');
const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.gif', '.webp', '.avif']);

function writeManifest(manifest, total, shelfCount) {
  const contents =
    '// AUTO-GENERATED by build-manifest.js — do not edit by hand.\n' +
    '// Re-run `node build-manifest.js` after adding/removing photos.\n' +
    'const PHOTOS = ' + JSON.stringify(manifest, null, 2) + ';\n';

  fs.writeFileSync(OUT_FILE, contents);
  console.log(`\nWrote ${OUT_FILE} (${total} photo(s) across ${shelfCount} shelf(ves))`);
}

function buildByPerson() {
  const manifest = {};

  if (!fs.existsSync(PHOTOS_DIR)) {
    fs.mkdirSync(PHOTOS_DIR);
  }

  const topEntries = fs.readdirSync(PHOTOS_DIR, { withFileTypes: true });

  const looseAtRoot = topEntries.filter(e => e.isFile() && IMAGE_EXT.has(path.extname(e.name).toLowerCase()));
  if (looseAtRoot.length > 0) {
    console.warn(`Skipping ${looseAtRoot.length} photo(s) directly in photos/ — move them into photos/<Person>/<Book>/ first.`);
  }

  const people = topEntries.filter(e => e.isDirectory()).map(e => e.name).sort();

  let total = 0;

  for (const person of people) {
    const personPath = path.join(PHOTOS_DIR, person);
    const bookEntries = fs.readdirSync(personPath, { withFileTypes: true });

    const looseInPerson = bookEntries.filter(e => e.isFile() && IMAGE_EXT.has(path.extname(e.name).toLowerCase()));
    if (looseInPerson.length > 0) {
      console.warn(`Skipping ${looseInPerson.length} photo(s) directly in photos/${person}/ — move them into a book subfolder, e.g. photos/${person}/Misc/`);
    }

    const bookNames = bookEntries.filter(e => e.isDirectory()).map(e => e.name).sort();

    const books = {};
    for (const book of bookNames) {
      const bookPath = path.join(personPath, book);
      const files = fs.readdirSync(bookPath)
        .filter(f => IMAGE_EXT.has(path.extname(f).toLowerCase()))
        .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

      if (files.length === 0) continue;

      books[book] = files.map(f => `photos/${person}/${book}/${f}`);
      total += files.length;
      console.log(`${person}/${book}: ${files.length} photo(s)`);
    }

    if (Object.keys(books).length > 0) {
      manifest[person] = books;
    }
  }

  writeManifest(manifest, total, Object.keys(manifest).length);
}

// --- Old date-based build, kept for reference / easy revert. Unused. ---
function buildByDate() {
  const FOLDER_RE = /^(\d{4})-(\d{2})$/;
  const manifest = {};

  if (!fs.existsSync(PHOTOS_DIR)) {
    fs.mkdirSync(PHOTOS_DIR);
  }

  const entries = fs.readdirSync(PHOTOS_DIR, { withFileTypes: true })
    .filter(e => e.isDirectory())
    .map(e => e.name)
    .sort();

  let total = 0;

  for (const folderName of entries) {
    const match = FOLDER_RE.exec(folderName);
    if (!match) {
      console.warn(`Skipping "${folderName}" (expected YYYY-MM, e.g. 2026-07)`);
      continue;
    }
    const year = parseInt(match[1], 10);
    const monthIdx = parseInt(match[2], 10) - 1; // 0-11 to match MONTHS array

    const folderPath = path.join(PHOTOS_DIR, folderName);
    const files = fs.readdirSync(folderPath)
      .filter(f => IMAGE_EXT.has(path.extname(f).toLowerCase()))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

    if (files.length === 0) continue;

    manifest[`${year}-${monthIdx}`] = files.map(f => `photos/${folderName}/${f}`);
    total += files.length;
    console.log(`${folderName}: ${files.length} photo(s)`);
  }

  writeManifest(manifest, total, Object.keys(manifest).length);
}

buildByPerson();
